-- Q9. Find employees whose total sales are greater than the average
-- total sales of all employees who have made at least one sale.
-- Display employee name and total sales.
-- This requires comparing each employee's aggregated sales against
-- an aggregated value calculated from other employees.

SELECT 
    e.emp_name,
    (
        SELECT SUM(s.amount)
        FROM sales s
        WHERE s.emp_id = e.emp_id
    ) AS total_sales
FROM employees e
WHERE (
    SELECT SUM(s.amount)
    FROM sales s
    WHERE s.emp_id = e.emp_id
) > (
    SELECT AVG(employee_total)
    FROM (
        SELECT 
            s2.emp_id,
            SUM(s2.amount) AS employee_total
        FROM sales s2
        GROUP BY s2.emp_id
    ) AS totals
);

-- Q10. Find employees who have made a sale in every month in which
-- at least one sale occurred.
-- Display employee name.
-- Use a correlated subquery / NOT EXISTS approach.
-- This is an interview-level relational division problem.

SELECT e.emp_name
FROM employees e
WHERE NOT EXISTS (
    SELECT 1
    FROM (
        SELECT DISTINCT MONTH(s.sale_date) AS sale_month
        FROM sales s
    ) m
    WHERE NOT EXISTS (
        SELECT 1
        FROM sales s2
        WHERE s2.emp_id = e.emp_id
          AND MONTH(s2.sale_date) = m.sale_month
    )
);
