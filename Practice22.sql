-- Q1. Find employees whose salary is greater than the average salary
-- of all employees.
-- Display employee name, department and salary.

select emp_name, department, salary from employees where salary > (select avg(salary) from employees);


-- Q2. Find employees who earn the highest salary in their department.
-- Display employee name, department and salary.
-- Do NOT use window functions.

select emp_name, department, salary from employees e1 
where salary = (select max(salary) 	from employees e2 where 
e2.department = e1.department);

-- Q3. Find employees whose salary is greater than the average salary
-- of their respective department.
-- Display employee name, department and salary.
-- Hint: The average salary must be calculated separately for each employee's department.

select emp_name, department, salary from employees e1 
where salary > (select avg(salary) from employees e2 where 
e2.department = e1.department);


-- Q4. Find the employee(s) who have generated the highest total sales.
-- Display employee name and total sales.
-- Use a subquery to compare each employee's total sales with the maximum
-- total sales generated by any employee.

select e.emp_name, sum(s.amount) as total_sales from employees e left join sales s on
e.emp_id = s.emp_id group by e.emp_id, e.emp_name HAVING SUM(s.amount) = (
    SELECT MAX(emp_total.total_sales)
    FROM (
        SELECT SUM(amount) AS total_sales
        FROM sales
        GROUP BY emp_id
    ) AS emp_total
);


-- Q5. Find employees who have made at least one sale greater than
-- the average sale amount of ALL sales.
-- Display employee name and sale amount.
-- Use EXISTS or a correlated subquery.

SELECT emp_name
FROM employees e
WHERE EXISTS (
    SELECT 1
    FROM sales s
    WHERE s.emp_id = e.emp_id
      AND s.amount > 100000
);




-- Q6. Find employees whose salary is greater than their manager's salary.
-- Display employee name, employee salary, manager name and manager salary.
-- Solve this using a correlated subquery rather than a normal JOIN.


SELECT 
    e.emp_name AS employee_name,
    e.salary AS employee_salary,
    (
        SELECT m.emp_name
        FROM employees m
        WHERE m.emp_id = e.manager_id
    ) AS manager_name,
    (
        SELECT m.salary
        FROM employees m
        WHERE m.emp_id = e.manager_id
    ) AS manager_salary
FROM employees e
WHERE e.salary > (
    SELECT m.salary
    FROM employees m
    WHERE m.emp_id = e.manager_id
);

-- Q7. Find employees who have NOT generated any sales.
-- Display employee name and department.
-- Solve using NOT EXISTS.

